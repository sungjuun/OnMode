import { expect, test } from '@playwright/test'

test('furniture rotates and resizes with bounded movement, save, reload, cancel and reset', async ({ page }, info) => {
  await page.emulateMedia({ colorScheme: info.project.name === 'mobile' ? 'dark' : 'light' })
  await page.goto('/growth')
  const desk = page.locator('[data-room-item="desk"]')
  await page.getByRole('button', { name: '배치 편집', exact: true }).click()
  await page.getByRole('button', { name: '원목 책상 선택', exact: true }).click()
  const controls = page.getByRole('group', { name: '가구 회전과 크기', exact: true })
  await expect(controls.getByRole('button', { name: '선택 가구 모양 초기화' })).toBeDisabled()
  await controls.getByRole('button', { name: '오른쪽 회전', exact: true }).click()
  await controls.getByRole('combobox', { name: '가구 크기' }).selectOption('120')
  await expect(desk).toHaveAttribute('data-room-rotation', '90')
  await expect(desk).toHaveAttribute('data-room-scale', '120')
  await expect(desk).toHaveAttribute('transform', 'translate(0 -66)')
  // Arrow keys remain in room coordinates after rotation; boundary clamps the tall shape.
  await desk.focus(); await desk.press('ArrowDown'); await desk.press('ArrowRight')
  await expect(desk).toHaveAttribute('transform', 'translate(5 -66)')
  await desk.press('Shift+ArrowUp')
  await expect(desk).toHaveAttribute('transform', 'translate(5 -67)')
  await expect(desk.locator('.room-hit-area')).toHaveAttribute('transform', /rotate\(90\).*scale\(1.2\)/)
  await page.screenshot({ path: info.outputPath('room-transforms.png'), scale: 'css', fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(page.viewportSize()!.width)
  await page.getByRole('button', { name: '배치 저장', exact: true }).click()
  await expect(page.getByRole('button', { name: '배치 편집', exact: true })).toBeVisible()
  await page.reload()
  await expect(desk).toHaveAttribute('data-room-rotation', '90')
  await expect(desk).toHaveAttribute('data-room-scale', '120')
  await expect(desk).toHaveAttribute('transform', 'translate(5 -67)')
  await page.getByRole('button', { name: '배치 편집', exact: true }).click()
  const canvas = page.getByRole('group', { name: '공부방 배치 편집', exact: true })
  await canvas.scrollIntoViewIfNeeded()
  const box = (await canvas.boundingBox())!
  const start = { x: box.x + box.width * 370 / 640, y: box.y + box.height * 180 / 356 }
  const end = { x: start.x + box.width * 20 / 640, y: start.y }
  if (info.project.name === 'mobile') {
    const touch = await page.context().newCDPSession(page)
    await touch.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ ...start, id: 0 }] })
    await touch.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ ...end, id: 0 }] })
    await touch.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
    await touch.detach()
  } else {
    await page.mouse.move(start.x, start.y); await page.mouse.down()
    await page.mouse.move(end.x, end.y, { steps: 5 }); await page.mouse.up()
  }
  await expect(desk).toHaveAttribute('transform', 'translate(25 -67)')
  await page.getByRole('button', { name: '취소', exact: true }).click()
  await expect(desk).toHaveAttribute('transform', 'translate(5 -67)')
  await page.getByRole('button', { name: '원목 책상 치우기', exact: true }).click()
  await page.getByRole('button', { name: '원목 책상 배치', exact: true }).click()
  await expect(desk).toHaveAttribute('data-room-rotation', '90')
  await page.getByRole('button', { name: '배치 편집', exact: true }).click()
  await page.getByRole('button', { name: '원목 책상 선택', exact: true }).click()
  await controls.getByRole('button', { name: '선택 가구 모양 초기화' }).click()
  await expect(desk).toHaveAttribute('data-room-rotation', '0')
  await expect(desk).toHaveAttribute('data-room-scale', '100')
  await expect(desk).toHaveAttribute('transform', 'translate(5 -33)')
  await page.getByRole('button', { name: '취소', exact: true }).click()
  await expect(desk).toHaveAttribute('data-room-rotation', '90')
  await page.getByRole('button', { name: '배치 편집', exact: true }).click()
  await page.getByRole('button', { name: '기본 위치', exact: true }).click()
  await page.getByRole('button', { name: '배치 저장', exact: true }).click()
  await page.reload()
  await expect(desk).toHaveAttribute('data-room-scale', '100')
  await expect(desk).toHaveAttribute('data-room-rotation', '0')
  await expect(desk).toHaveAttribute('transform', 'translate(0 0)')
  await page.getByRole('button', { name: '배치 편집', exact: true }).click()
  await page.getByRole('button', { name: '라벤더 의자 선택', exact: true }).click()
  await controls.getByRole('button', { name: '오른쪽 회전', exact: true }).click()
  await controls.getByRole('combobox', { name: '가구 크기' }).selectOption('80')
  await page.locator('.room-card').screenshot({ path: info.outputPath('room-transforms-preview.png'), scale: 'css' })
})
