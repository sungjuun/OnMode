import { expect, test } from '@playwright/test'

test('personal study needs no exam and keeps its journal, focus and home summary after reload', async ({ page }, info) => {
  await page.emulateMedia({ colorScheme: info.project.name === 'mobile' ? 'dark' : 'light' })
  await page.clock.install({ time: new Date('2026-11-05T09:00:00+09:00') })
  await page.goto('/library')
  await expect(page.getByText('등록된 공부가 없어요', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '등록', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '공부 등록' })
  await expect(dialog.getByRole('combobox', { name: '등록 유형' })).toHaveValue('subject')
  await expect(dialog.getByLabel('시험일', { exact: true })).toHaveCount(0)
  await dialog.getByRole('textbox', { name: '공부 이름' }).fill('   ')
  await dialog.getByRole('button', { name: '저장', exact: true }).click()
  await expect(dialog.getByRole('alert')).toHaveText('이름을 입력해 주세요.')
  await dialog.getByRole('textbox', { name: '공부 이름' }).fill('  영어 회화  ')
  await dialog.getByRole('spinbutton', { name: '목표 시간 (분)', exact: true }).fill('1')
  // Choosing an optional certification must not erase the personal-study draft.
  await dialog.getByRole('combobox', { name: '등록 유형' }).selectOption('certification')
  await dialog.getByRole('textbox', { name: '자격증 이름' }).fill('선택 초안')
  await dialog.getByRole('combobox', { name: '등록 유형' }).selectOption('subject')
  await expect(dialog.getByRole('textbox', { name: '공부 이름' })).toHaveValue('  영어 회화  ')
  await expect(dialog.getByRole('spinbutton', { name: '목표 시간 (분)', exact: true })).toHaveValue('1')
  await page.screenshot({ path: info.outputPath('study-registration.png'), fullPage: true })
  await dialog.getByRole('button', { name: '저장', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: '영어 회화', exact: true })).toBeVisible()
  await expect(page.getByText('등록된 공부가 없어요', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '학습 기록' }).click()
  await page.getByLabel('푼 문제 수').fill('3')
  await page.getByLabel('공부한 내용').fill('일상 표현 연습')
  await page.getByRole('button', { name: '저장', exact: true }).click()
  await page.getByText('저장한 기록 1개', { exact: true }).click()
  await expect(page.getByText('일상 표현 연습', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: '집중하기', exact: true }).click()
  await expect(page.getByRole('combobox', { name: '집중할 활동' }).locator('option:checked')).toHaveText('공부 · 영어 회화')
  await page.getByRole('button', { name: /플로우타임/ }).click()
  await page.getByRole('button', { name: '집중 시작', exact: true }).click()
  await expect(page.getByRole('button', { name: '일시정지' })).toBeVisible()
  await page.clock.fastForward(65_000)
  await page.getByRole('button', { name: '종료하고 저장' }).click()
  await expect(page.getByText(/\+5 XP · \+1 코인/)).toBeVisible()
  await page.goto('/library')
  await expect(page.getByRole('progressbar', { name: '영어 회화 진행률' })).toHaveAttribute('aria-valuenow', '100')
  await page.screenshot({ path: info.outputPath('personal-study.png'), fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(page.viewportSize()!.width)
  await page.goto('/')
  await expect(page.getByRole('link').filter({ hasText: '영어 회화' })).toContainText('누적 집중 1분 · 목표 1분')
})
