import { expect, test } from '@playwright/test'

test('study and reading, restored timer, rewards and room', async ({ page }, info) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await page.clock.install({ time: new Date('2026-11-04T09:00:00+09:00') })
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '안녕하세요, 집중러님!' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(page.viewportSize()!.width)
  await page.screenshot({ path: info.outputPath('dashboard.png'), fullPage: true })
  await page.getByRole('link', { name: '학습·독서', exact: true }).click()
  await page.getByRole('button', { name: '등록', exact: true }).click()
  await page.getByRole('combobox', { name: '등록 유형' }).selectOption('certification')
  await page.getByLabel('자격증 이름').fill('SQLD')
  await page.getByLabel('시험일').fill('2026-12-01')
  await page.getByRole('button', { name: '저장', exact: true }).click()
  await page.getByRole('button', { name: '과목 추가' }).click()
  await page.getByLabel('과목 이름').fill('데이터베이스')
  await page.getByRole('button', { name: '저장', exact: true }).click()
  await expect(page.getByRole('heading', { name: '데이터베이스' })).toBeVisible()
  await page.getByRole('button', { name: '학습 기록' }).click()
  await page.getByLabel('푼 문제 수').fill('8')
  await page.getByLabel('공부한 내용').fill('정규화 문제 풀이')
  await page.getByRole('button', { name: '저장', exact: true }).click()

  await page.getByRole('button', { name: '나의 서재' }).click()
  await page.getByRole('button', { name: '도서 등록' }).click()
  await page.getByLabel('책 제목').fill('집중의 기술')
  await page.getByLabel('저자').fill('테스트 저자')
  await page.getByLabel('총 페이지').fill('100')
  await page.getByRole('button', { name: '저장', exact: true }).click()
  await page.getByRole('button', { name: '독서 기록' }).click()
  await page.getByLabel('현재 읽은 페이지').fill('35')
  await page.getByLabel('독서 노트 / 후기').fill('집중을 위한 메모')
  await page.getByRole('button', { name: '저장', exact: true }).click()
  await expect(page.getByRole('progressbar', { name: '집중의 기술 진행률' })).toHaveAttribute('aria-valuenow', '35')

  await page.getByRole('link', { name: '집중하기' }).click()
  await page.getByRole('button', { name: /플로우타임/ }).click()
  await page.getByRole('button', { name: '집중 시작', exact: true }).click()
  await expect(page.getByRole('button', { name: '일시정지' })).toBeVisible()
  await page.clock.fastForward(31_000)
  await page.getByRole('button', { name: '일시정지' }).click()
  await expect(page.getByRole('button', { name: '재개' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button', { name: '재개' })).toBeVisible()
  const before = await page.locator('[aria-label="타이머"]').textContent()
  await page.clock.fastForward(60_000)
  await expect(page.locator('[aria-label="타이머"]')).toHaveText(before!)
  await page.getByRole('button', { name: '재개' }).click()
  await expect(page.getByRole('button', { name: '일시정지' })).toBeVisible()
  await page.clock.fastForward(31_000)
  await page.getByRole('button', { name: '종료하고 저장' }).click()
  await expect(page.getByText(/\+5 XP · \+1 코인/)).toBeVisible()

  await page.getByRole('link', { name: '성장', exact: true }).click()
  await page.getByRole('button', { name: '새벽 조명 구매' }).click()
  await page.getByRole('button', { name: '새벽 조명 배치' }).click()
  await expect(page.getByText('3개 배치됨')).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button', { name: '새벽 조명 치우기' })).toBeVisible()
  await page.getByRole('link', { name: 'MY', exact: true }).click()
  await expect(page.getByRole('heading', { name: '집중 기록', exact: true })).toBeVisible()
  await expect(page.getByText('1회 기록')).toBeVisible()
  await page.getByRole('link', { name: '스터디', exact: true }).click()
  await expect(page.getByText('스터디 체험 안내')).toBeVisible()
  expect(errors).toEqual([])
})

test('all modes render and custom timer restores and finishes after background time', async ({ page }) => {
  await page.clock.install({ time: new Date('2026-11-04T09:00:00+09:00') })
  await page.goto('/focus')
  const timer = page.locator('[aria-label="타이머"]')
  await expect(timer).toHaveText('25:00')
  await page.getByRole('button', { name: /50\/10/ }).click()
  await expect(timer).toHaveText('50:00')
  await page.getByRole('button', { name: /사용자 지정/ }).click()
  await page.getByLabel('집중 (분)').fill('1')
  await page.getByLabel('휴식 (분)').fill('2')
  await expect(timer).toHaveText('01:00')
  await page.getByRole('button', { name: '집중 시작', exact: true }).click()
  await expect(page.getByRole('button', { name: '일시정지' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button', { name: '일시정지' })).toBeVisible()
  await page.clock.fastForward(75_000)
  await expect(page.getByRole('button', { name: '휴식 종료' })).toBeVisible()
  await expect(page.getByText(/\+5 XP · \+1 코인/)).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button', { name: '휴식 종료' })).toBeVisible()
  await page.getByRole('button', { name: '휴식 종료' }).click()
  await expect(page.getByRole('button', { name: '집중 시작', exact: true })).toBeVisible()
})
